const URBANGUARD_LANGS = {
  en:'English', hi:'हिन्दी', ta:'தமிழ்', te:'తెలుగు', bn:'বাংলা',
  mr:'मराठी', gu:'ગુજરાતી', kn:'ಕನ್ನಡ', ml:'മലയാളം', or:'ଓଡ଼ିଆ',
  pa:'ਪੰਜਾਬੀ', as:'অসমীয়া', ur:'اردو', sa:'संस्कृतम्',
  ne:'नेपाली', mai:'मैथिली', kok:'कोंकणी'
};

/** Get current language from localStorage */
function getCurrentLang(){
  return localStorage.getItem('ug_lang') || 'en';
}

/** Get translation for a key in current language */
function t(key, replacements){
  const lang = getCurrentLang();
  const dict = URBANGUARD_TRANSLATIONS[lang] || URBANGUARD_TRANSLATIONS.en;
  let text = dict[key] || URBANGUARD_TRANSLATIONS.en[key] || key;
  if(replacements){
    Object.keys(replacements).forEach(k => {
      text = text.replace(`{${k}}`, replacements[k]);
    });
  }
  return text;
}

/** Apply translations to all [data-i18n] elements in the page */
function applyTranslations(){
  const lang = getCurrentLang();
  document.documentElement.setAttribute('lang', lang);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if(val) el.textContent = val;
  });

  // Translate placeholders
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    const val = t(key);
    if(val) el.placeholder = val;
  });

  // Translate value attributes for options
  document.querySelectorAll('[data-i18n-val]').forEach(el => {
    const key = el.getAttribute('data-i18n-val');
    const val = t(key);
    if(val) el.value = val;
  });
}

/** Change language globally */
function setLang(lang){
  if(!URBANGUARD_TRANSLATIONS[lang]) lang = 'en';
  localStorage.setItem('ug_lang', lang);
  applyTranslations();
  if(typeof onLangChange === 'function') onLangChange(lang);
}

// Expose globally
window.URBANGUARD_TRANSLATIONS = URBANGUARD_TRANSLATIONS;
window.URBANGUARD_LANGS = URBANGUARD_LANGS;
window.getCurrentLang = getCurrentLang;
window.t = t;
window.applyTranslations = applyTranslations;
window.setLang = setLang;